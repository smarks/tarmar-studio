if DATABASE_URL:  # pragma: no cover
    # PostgreSQL for production. dj-database-url handles passwords with special
    # characters, query params (e.g. ?sslmode=require), and an optional port,
    # which the previous hand-rolled regex did not. CONN_MAX_AGE reuses
    # connections across requests instead of opening one per request.
    import dj_database_url  # type: ignore[import-not-found]  # prod-only dep

    DATABASES = {
        "default": dj_database_url.parse(DATABASE_URL, conn_max_age=600),
    }
else:
    # SQLite for development. The three OPTIONS exist for concurrent access —
    # the threaded runserver handles parallel Playwright workers (and a human
    # clicking around during a battle simulation) on one SQLite file:
    #
    # - transaction_mode IMMEDIATE takes the write lock at BEGIN. Django's
    #   default deferred transactions start as reads and upgrade on the first
    #   write; when two connections do that concurrently the upgrade returns
    #   "database is locked" instantly, without ever consulting the busy
    #   timeout (SQLite refuses to wait on a would-be deadlock). Login POSTs
    #   died this way whenever they raced a battle-advance transaction.
    # - journal_mode WAL lets readers proceed while a writer commits, so a
    #   long write transaction no longer blocks every other request.
    # - timeout 20 (seconds) is how long a writer waits for another writer,
    #   up from the 5s default.
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
            "OPTIONS": {
                "transaction_mode": "IMMEDIATE",
                "timeout": 20,
                "init_command": "PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL;",
            },
        }
    }


# Cache
# https://docs.djangoproject.com/en/5.2/topics/cache/
#
# Rate limiting is the only thing here that uses the cache, and it is a security
# control, so the cache has to be shared. Django's default when CACHES is unset
# is a per-process LocMemCache: every gunicorn worker kept its own counters, so
# each limit was silently multiplied by the worker count and reset on every
# blue-green restart (issue #139). DatabaseCache gives one set of counters for
# the whole site — across workers and across restarts — without standing up
# Redis or memcached. Its table is created by common/migrations/0001_...py, so
# deploy.sh's existing `manage.py migrate` step covers it; no new deploy step.
CACHE_TABLE_NAME = "tarmar_cache_table"

CACHES = {
    "default": {
        "BACKEND": "django.core.cache.backends.db.DatabaseCache",
        "LOCATION": CACHE_TABLE_NAME,
        "OPTIONS": {
            # Django's default MAX_ENTRIES is 300, and DatabaseCache culls a
            # third of the table once it is passed. Counters are now per client
            # IP, so a busy hour — or a distributed guessing run — would push
            # past 300 and cull away the very counters holding attackers back.
            # Rows here are tiny and short-lived, so buy headroom.
            "MAX_ENTRIES": 20000,
        },
    }
}


