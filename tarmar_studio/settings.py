# Trust the reverse proxy's client-IP headers (X-Real-IP, then the last hop of
# X-Forwarded-For). Off by default: with the app reachable directly those
# headers are attacker-controlled, and honouring them would let one caller
# forge an identity per request and slip every per-IP rate limit. Turn it on
# ONLY where every request arrives through nginx, which overwrites both headers
# (see nginx/tarmar.conf and common.helpers.client_ip). Off, per-client limits
# behind the proxy collapse into one shared site-wide bucket.
