# Wall-clock budget for one streamed GM turn (issue #361). Past this the view
# stops reading from Ollama and sends the player an error frame instead of
# leaving them on a connection that never finishes. It was 180 s, roughly twice
# the slowest turn then measured on the Mac Studio. Character creation has
# outgrown that: a Game Master asking for twins with stated scores and two runs
# of years measured 171-249 s on production in September 2026, and three of
# five such turns finished past 180 s while one was cut off (issue #554). 300 s
# covers those turns as they are actually taking, and the budget is checked
# between tokens and on keep-alives, so a model that has genuinely gone cold is
# still ended rather than waited on to the end of the budget. The cost of
# raising it is only that a wedged turn takes longer to tell the player
# something. Lower it again if #554's folding brings those turns back under
# about 120 s.
GM_STREAM_BUDGET_SECONDS = float(os.environ.get("GM_STREAM_BUDGET_SECONDS", "300"))

# Wall-clock budget for the recap a continued session's first turn writes
# before the turn starts (issue #936). It runs before the turn's own clock by
